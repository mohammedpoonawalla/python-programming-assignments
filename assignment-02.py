mass = float(input("Enter the mass of the object in kg: "))

gravity_earth = 9.8
weight_earth = mass*gravity_earth
gravity_moon = 1.62
weight_moon = mass*gravity_moon
print(f"The weight of the object on Earth is {weight_earth:.2f} N") 
print(f"The weight of the object on the Moon is {weight_moon:.2f} N")





